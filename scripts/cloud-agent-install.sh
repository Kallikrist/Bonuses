// ${MARKER}
// Local payment bookkeeping used by the admin UI and payment tests.
import 'package:bonuses/models/financial_transaction.dart';
import 'package:bonuses/models/payment_card.dart';
import 'package:bonuses/models/payment_record.dart';
import 'package:bonuses/services/storage_service.dart';

class PaymentService {
  static int _seq = 0;

  static String _id(String prefix) {
    _seq += 1;
    return '\${prefix}_\${DateTime.now().microsecondsSinceEpoch}_\$_seq';
  }

  static ({CardType type, String brand}) _detectCard(String cardNumber) {
    final digits = cardNumber.replaceAll(RegExp(r'\\s'), '');
    if (digits.startsWith('4') && digits.length >= 13) {
      return (type: CardType.visa, brand: 'Visa');
    }
    if (RegExp(r'^5[1-5]').hasMatch(digits) && digits.length >= 16) {
      return (type: CardType.mastercard, brand: 'Mastercard');
    }
    if ((digits.startsWith('34') || digits.startsWith('37')) &&
        digits.length >= 15) {
      return (type: CardType.americanExpress, brand: 'American Express');
    }
    return (type: CardType.unknown, brand: 'Unknown');
  }

  static Future<PaymentCard?> addPaymentCard({
    required String companyId,
    required String userId,
    required String cardNumber,
    required int expiryMonth,
    required int expiryYear,
    required String cvc,
    String? cardholderName,
  }) async {
    final detected = _detectCard(cardNumber);
    final digits = cardNumber.replaceAll(RegExp(r'\\s'), '');
    final lastFour =
        digits.length >= 4 ? digits.substring(digits.length - 4) : digits;
    final existing = await StorageService.getPaymentCards();
    final hasDefault = existing.any(
      (card) => card.companyId == companyId && card.isDefault,
    );
    final card = PaymentCard(
      id: _id('card'),
      companyId: companyId,
      userId: userId,
      lastFourDigits: lastFour,
      brand: detected.brand,
      cardType: detected.type,
      expiryMonth: expiryMonth,
      expiryYear: expiryYear,
      cardholderName: cardholderName,
      status: CardStatus.active,
      createdAt: DateTime.now(),
      isDefault: !hasDefault,
    );
    await StorageService.addPaymentCard(card);
    return card;
  }

  static Future<List<PaymentCard>> getCompanyPaymentCards(
    String companyId,
  ) async {
    final cards = await StorageService.getPaymentCards();
    return cards.where((card) => card.companyId == companyId).toList();
  }

  static Future<void> setDefaultCard(String cardId) async {
    final cards = await StorageService.getPaymentCards();
    final target = cards.cast<PaymentCard?>().firstWhere(
          (card) => card!.id == cardId,
          orElse: () => null,
        );
    if (target == null) {
      return;
    }
    final updated = cards
        .map(
          (card) => card.copyWith(
            isDefault: card.companyId == target.companyId && card.id == cardId,
          ),
        )
        .toList();
    await StorageService.savePaymentCards(updated);
  }

  static Future<void> deletePaymentCard(String cardId) async {
    await StorageService.deletePaymentCard(cardId);
  }

  static Future<FinancialTransaction?> processPayment({
    required String companyId,
    required String userId,
    required String cardId,
    required double amount,
    required String description,
    required TransactionType type,
    required TransactionCategory category,
  }) async {
    final card = await StorageService.getPaymentCardById(cardId);
    final now = DateTime.now();
    if (card == null) {
      final failed = FinancialTransaction(
        id: _id('txn'),
        companyId: companyId,
        userId: userId,
        type: type,
        status: TransactionStatus.failed,
        category: category,
        amount: amount,
        description: description,
        createdAt: now,
        paymentCardId: cardId,
        failureReason: 'Payment card not found',
        paymentGateway: 'mock',
      );
      await StorageService.addFinancialTransaction(failed);
      return failed;
    }

    final transaction = FinancialTransaction(
      id: _id('txn'),
      companyId: companyId,
      userId: userId,
      type: type,
      status: TransactionStatus.completed,
      category: category,
      amount: amount,
      description: description,
      createdAt: now,
      completedAt: now,
      paymentCardId: card.id,
      paymentGateway: 'mock',
    );
    await StorageService.addFinancialTransaction(transaction);
    return transaction;
  }

  static Future<PaymentRecord?> processSubscriptionPayment({
    required String companyId,
    required String subscriptionId,
    required double amount,
    required String cardId,
  }) async {
    final record = PaymentRecord(
      id: _id('pay'),
      companyId: companyId,
      subscriptionId: subscriptionId,
      amount: amount,
      status: PaymentStatus.completed,
      date: DateTime.now(),
      transactionId: cardId,
      paymentGateway: 'mock',
    );
    await StorageService.addPaymentRecord(record);
    return record;
  }

  static Future<FinancialTransaction?> refundTransaction({
    required String transactionId,
    required double refundAmount,
    String? reason,
  }) async {
    final existing =
        await StorageService.getFinancialTransactionById(transactionId);
    if (existing == null) {
      return null;
    }
    final fullyRefunded = refundAmount >= existing.amount;
    final updated = existing.copyWith(
      status: fullyRefunded
          ? TransactionStatus.refunded
          : TransactionStatus.partiallyRefunded,
      refundedAmount: refundAmount,
      refundedAt: DateTime.now(),
      failureReason: reason,
    );
    await StorageService.updateFinancialTransaction(updated);
    return updated;
  }

  static Future<List<FinancialTransaction>> getCompanyTransactions(
    String companyId,
  ) async {
    final transactions = await StorageService.getFinancialTransactions();
    return transactions.where((tx) => tx.companyId == companyId).toList();
  }
}
