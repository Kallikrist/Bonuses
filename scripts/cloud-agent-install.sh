#!/usr/bin/env bash
# Idempotent Cloud Agent bootstrap for the Bonuses Flutter app.
# Installs Dart packages and recreates gitignored sources required to compile.
set -euo pipefail

# Stay in the checkout when this script is invoked from the snapshot copy
# at /opt/cursor. Resolve the repo root only when the current directory is
# not already the Flutter project.
if [[ -f "${PWD}/pubspec.yaml" ]]; then
  ROOT="${PWD}"
else
  ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
  cd "$ROOT"
fi

export PATH="/opt/flutter/bin:${PATH}"

if ! command -v flutter >/dev/null 2>&1; then
  echo "flutter is not on PATH. The Cloud Agent image should provide /opt/flutter/bin." >&2
  exit 1
fi

MARKER="Generated by scripts/cloud-agent-install.sh"

write_generated() {
  local path="$1"
  mkdir -p "$(dirname "$path")"
  if [[ -f "$path" ]] && ! grep -q "$MARKER" "$path"; then
    echo "Keeping existing ${path} (not generated by this script)."
    return 0
  fi
  cat >"$path"
  echo "Wrote ${path}"
}

